// G-code generator for Rep5x vase generator

class GcodeGenerator {
    constructor() {
        this.shapes = {};
    }

    registerShape(name, shapeInstance) {
        this.shapes[name] = shapeInstance;
    }

    generate(shapeName, shapeParams, printSettings, advancedSettings) {
        const shape = this.shapes[shapeName];
        if (!shape) {
            throw new Error(`Unknown shape: ${shapeName}`);
        }

        const { layerHeight, speed, nozzleDiameter, nozzleTemp, bedTemp, bedWidth, bedDepth } = printSettings;
        const { enableKinematics, laParam, lbParam, enableAAxisOptimization, startGcode, endGcode } = advancedSettings;

        const gcode = [];
        const totalHeight = shape.getTotalHeight(shapeParams);
        const bedCenterX = bedWidth / 2;
        const bedCenterY = bedDepth / 2;

        // Process start/end G-code - replace placeholders
        let processedStartGcode = this.processTemplatePlaceholders(startGcode, {
            nozzleTemp, bedTemp, bedCenterX, bedCenterY
        });
        let processedEndGcode = this.processTemplatePlaceholders(endGcode, {
            nozzleTemp, bedTemp, totalHeight
        });

        // Header
        gcode.push('; Generated by Rep5x Vase Generator');
        gcode.push(`; Shape: ${shapeName}`);
        this.addShapeHeader(gcode, shapeName, shapeParams);
        gcode.push(`; Nozzle Diameter: ${nozzleDiameter}mm`);
        gcode.push(`; Layer Height: ${layerHeight}mm`);
        gcode.push(`; Print Speed: ${speed / 60}mm/s`);
        gcode.push(`; Generated on: ${new Date().toISOString()}`);
        gcode.push('');

        // 5-axis and IK parameters
        gcode.push('; === Rep5x Parameters ===');
        gcode.push(`; Inverse Kinematics: ${enableKinematics ? 'enabled' : 'disabled'}`);
        if (enableKinematics) {
            gcode.push(`; LA Parameter: ${laParam}`);
            gcode.push(`; LB Parameter: ${lbParam}`);
            gcode.push('; IK Formulas:');
            gcode.push("; X = X' + sin(A') × LA + cos(A') × sin(B') × LB");
            gcode.push("; Y = Y' - LA + cos(A') × LA - sin(A') × sin(B') × LB");
            gcode.push("; Z = Z' + cos(B') × LB - LB");
        }
        gcode.push(`; A-axis Optimization: ${enableAAxisOptimization ? 'enabled' : 'disabled'}`);
        gcode.push('');

        // Start sequence
        gcode.push('; Start sequence');
        if (processedStartGcode.trim()) {
            gcode.push(...processedStartGcode.split('\n'));
        } else {
            this.addDefaultStartGcode(gcode);
        }
        gcode.push('M83 ; Use relative extrusion');
        gcode.push('');

        // Generate shape-specific G-code
        const shapeGcode = shape.generateGcode(shapeParams, layerHeight, speed);
        gcode.push(...shapeGcode);

        // End sequence
        gcode.push('');
        gcode.push('; End sequence');
        if (processedEndGcode.trim()) {
            const finalEndGcode = processedEndGcode.replace(/{print_height}/g, totalHeight);
            gcode.push(...finalEndGcode.split('\n'));
        } else {
            this.addDefaultEndGcode(gcode, totalHeight);
        }

        let gcodeString = gcode.join('\n');

        // Apply inverse kinematics if enabled
        if (enableKinematics) {
            gcodeString = processInverseKinematics(gcodeString, enableKinematics, laParam, lbParam);
        }

        // Apply A-axis optimization if enabled
        if (enableAAxisOptimization) {
            gcodeString = optimizeAAxisRotation(gcodeString, enableAAxisOptimization);
            gcodeString = addAAxisOptimizationComment(gcodeString);
        }

        return {
            gcode: gcodeString,
            filename: shape.getFilename(shapeParams)
        };
    }

    processTemplatePlaceholders(template, values) {
        if (!template) return '';

        let result = template;

        // OrcaSlicer/BambuStudio style placeholders
        result = result.replace(/\[nozzle_temperature_initial_layer\]/g, values.nozzleTemp || 210);
        result = result.replace(/\[bed_temperature_initial_layer_single\]/g, values.bedTemp || 60);
        result = result.replace(/\[bed_center_x\]/g, values.bedCenterX || 100);
        result = result.replace(/\[bed_center_y\]/g, values.bedCenterY || 100);

        // Hardcoded M-codes (fallback)
        if (values.nozzleTemp) {
            result = result.replace(/M104 S\d+/g, `M104 S${values.nozzleTemp}`);
            result = result.replace(/M109 S\d+/g, `M109 S${values.nozzleTemp}`);
        }
        if (values.bedTemp) {
            result = result.replace(/M140 S\d+/g, `M140 S${values.bedTemp}`);
            result = result.replace(/M190 S\d+/g, `M190 S${values.bedTemp}`);
        }

        return result;
    }

    addShapeHeader(gcode, shapeName, params) {
        if (shapeName === 'mushroom') {
            gcode.push(`; Stem Diameter: ${params.stemDiameter}mm`);
            gcode.push(`; Stem Height: ${params.stemHeight}mm`);
            gcode.push(`; Cap Diameter: ${params.capDiameter}mm`);
            gcode.push(`; Cap Height: ${params.capHeight}mm`);
        } else {
            gcode.push(`; Diameter: ${params.diameter}mm`);
            gcode.push(`; Vertical Section: ${params.vertical}mm`);
            gcode.push(`; Horizontal Section: ${params.horizontal}mm`);
            gcode.push(`; Bend Angle: ${params.tilt}°`);
        }
    }

    addDefaultStartGcode(gcode) {
        gcode.push('G28 ; Home all axes');
        gcode.push('G1 Z5 F300 ; Lift Z');
        gcode.push('M104 S210 ; Set hotend temp');
        gcode.push('M140 S60 ; Set bed temp');
        gcode.push('M190 S60 ; Wait for bed');
        gcode.push('M109 S210 ; Wait for hotend');
        gcode.push('G92 E0 ; Reset extruder');
        gcode.push('G1 E10 F200 ; Prime extruder');
        gcode.push('G92 E0 ; Reset extruder');
        gcode.push('G21 ; Set units to millimeters');
        gcode.push('G90 ; Use absolute coordinates');
    }

    addDefaultEndGcode(gcode, totalHeight) {
        gcode.push('G1 E-2 F1800 ; Retract filament');
        gcode.push(`G1 Z${totalHeight + 10} F300 ; Lift Z`);
        gcode.push('G28 X Y ; Home X Y');
        gcode.push('M104 S0 ; Turn off hotend');
        gcode.push('M140 S0 ; Turn off bed');
        gcode.push('M84 ; Disable motors');
        gcode.push('M117 Print Complete! ; Display message');
    }

    downloadGcode(gcodeString, filename) {
        const blob = new Blob([gcodeString], { type: 'text/plain' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = filename;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }
}

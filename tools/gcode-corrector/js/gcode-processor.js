/**
 * G-code Processor
 * Parses G-code and applies IK and/or calibration corrections
 */

class GcodeProcessor {
    constructor() {
        this.corrector = null;  // CalibrationCorrector instance
        this.ik = null;         // InverseKinematics instance

        // Modal state (tracks current values if not specified in line)
        this.modalX = 0;
        this.modalY = 0;
        this.modalZ = 0;
        this.modalC = 0;
        this.modalB = 0;
        this.isAbsolute = true;  // G90 (absolute) vs G91 (relative) mode

        // Statistics
        this.stats = {
            totalLines: 0,
            processedLines: 0,
            ikCorrectedLines: 0,
            calibrationCorrectedLines: 0,
            maxCorrectionX: 0,
            maxCorrectionY: 0,
            maxCorrectionZ: 0
        };

        // Detected header info from input file
        this.detectedHeaders = null;
    }

    /**
     * Detect Rep5x headers in G-code
     * @param {string} gcode - Input G-code
     * @returns {Object} Detected settings from headers
     */
    detectHeaders(gcode) {
        const result = {
            hasRep5xHeaders: false,
            ikEnabled: false,
            ikType: null,  // 'software' or 'firmware'
            lc: null,
            lb: null,
            calibrationEnabled: false,
            calibrationMode: null,  // 'standard' or 'firmware IK mode'
            generator: null,  // e.g., 'Vase Generator'
            processedBy: null  // e.g., 'G-code Corrector'
        };

        // Only check the first 50 lines for headers
        const lines = gcode.split('\n').slice(0, 50);

        for (const line of lines) {
            const trimmed = line.trim();
            if (!trimmed.startsWith(';')) continue;

            // Check for Rep5x headers
            if (trimmed.includes('Rep5x')) {
                result.hasRep5xHeaders = true;
            }

            // Detect generator
            if (trimmed.includes('Generated by Rep5x')) {
                const match = trimmed.match(/Generated by Rep5x\s+(.+)/);
                if (match) result.generator = match[1].trim();
            }

            // Detect if processed by corrector
            if (trimmed.includes('Processed by Rep5x G-code Corrector')) {
                result.processedBy = 'G-code Corrector';
            }

            // Detect IK status
            if (trimmed.includes('Inverse Kinematics:')) {
                if (trimmed.includes('enabled')) {
                    result.ikEnabled = true;
                    if (trimmed.includes('software')) {
                        result.ikType = 'software';
                    } else if (trimmed.includes('firmware')) {
                        result.ikType = 'firmware';
                    } else {
                        result.ikType = 'software';  // Default assumption
                    }
                } else if (trimmed.includes('disabled')) {
                    result.ikEnabled = false;
                    result.ikType = 'disabled';
                }
            }

            // Detect LC parameter
            const lcMatch = trimmed.match(/;\s*LC\s*(?:Parameter)?:?\s*([-+]?\d*\.?\d+)/i);
            if (lcMatch) {
                result.lc = parseFloat(lcMatch[1]);
            }

            // Detect LB parameter
            const lbMatch = trimmed.match(/;\s*LB\s*(?:Parameter)?:?\s*([-+]?\d*\.?\d+)/i);
            if (lbMatch) {
                result.lb = parseFloat(lbMatch[1]);
            }

            // Detect calibration status
            if (trimmed.includes('Calibration Correction:')) {
                if (trimmed.includes('enabled')) {
                    result.calibrationEnabled = true;
                    if (trimmed.includes('firmware IK mode')) {
                        result.calibrationMode = 'firmware IK mode';
                    } else {
                        result.calibrationMode = 'standard';
                    }
                }
            }
        }

        this.detectedHeaders = result;
        return result;
    }

    /**
     * Get detected headers from last detectHeaders() call
     */
    getDetectedHeaders() {
        return this.detectedHeaders;
    }

    /**
     * Set calibration corrector
     */
    setCalibrationCorrector(corrector) {
        this.corrector = corrector;
    }

    /**
     * Set IK parameters
     */
    setIKParameters(lc, lb) {
        this.ik = new InverseKinematics(lc, lb);
    }

    /**
     * Reset modal state
     */
    reset() {
        this.modalX = 0;
        this.modalY = 0;
        this.modalZ = 0;
        this.modalC = 0;
        this.modalB = 0;
        this.isAbsolute = true;
        this.stats = {
            totalLines: 0,
            processedLines: 0,
            ikCorrectedLines: 0,
            calibrationCorrectedLines: 0,
            maxCorrectionX: 0,
            maxCorrectionY: 0,
            maxCorrectionZ: 0
        };
    }

    /**
     * Process entire G-code string
     * @param {string} gcode - Input G-code
     * @param {Object} options - Processing options
     *   - applyIK: boolean - Apply inverse kinematics (software IK)
     *   - applyCalibration: boolean - Apply calibration corrections
     *   - firmwareIK: boolean - If true, assume firmware handles IK (don't apply software IK)
     *   - precision: number - Decimal places for coordinates
     * @returns {string} Corrected G-code
     *
     * Modes:
     * 1. applyIK=true, firmwareIK=false: Software IK + optional calibration
     * 2. applyIK=false, firmwareIK=true: Calibration only (for firmware IK)
     * 3. applyIK=true, firmwareIK=true: Calibration only (firmwareIK takes precedence)
     *
     * For firmware IK: Calibration corrections are applied directly to tip coordinates.
     * This works because IK is linear in XYZ (IK just adds a constant offset based on A,B).
     */
    process(gcode, options = {}) {
        this.reset();

        const firmwareIK = options.firmwareIK === true;
        const applyIK = !firmwareIK && options.applyIK !== false && this.ik;
        const applyCalibration = options.applyCalibration !== false && this.corrector?.loaded;

        const lines = gcode.split('\n');
        const processedLines = [];

        // Add header comment in Rep5x standard format
        processedLines.push('; Processed by Rep5x G-code Corrector');
        processedLines.push(`; Processed on: ${new Date().toISOString()}`);
        processedLines.push('');
        processedLines.push('; === Rep5x Corrections Applied ===');
        if (applyIK) {
            processedLines.push('; Inverse Kinematics: enabled (software)');
            processedLines.push(`; LC Parameter: ${this.ik.lc.toFixed(2)}`);
            processedLines.push(`; LB Parameter: ${this.ik.lb.toFixed(2)}`);
        }
        if (applyCalibration) {
            if (firmwareIK) {
                processedLines.push('; Calibration Correction: enabled (firmware IK mode)');
            } else {
                processedLines.push('; Calibration Correction: enabled');
            }

            // Add Fourier coefficients so viewer can reverse the calibration
            const coeffs = this.corrector.getCoefficients();
            if (coeffs.c) {
                processedLines.push(`; Calibration C-axis coefficients (Fourier, ${coeffs.cHarmonics} harmonics):`);
                processedLines.push(`; CalibCX: ${coeffs.c.x.map(c => c.toFixed(6)).join(',')}`);
                processedLines.push(`; CalibCY: ${coeffs.c.y.map(c => c.toFixed(6)).join(',')}`);
                processedLines.push(`; CalibCZ: ${coeffs.c.z.map(c => c.toFixed(6)).join(',')}`);
            }
            if (coeffs.b) {
                processedLines.push(`; Calibration B-axis coefficients (Harmonic, ${coeffs.bHarmonics} harmonics):`);
                processedLines.push(`; CalibBX: ${coeffs.b.x.map(c => c.toFixed(6)).join(',')}`);
                processedLines.push(`; CalibBY: ${coeffs.b.y.map(c => c.toFixed(6)).join(',')}`);
                processedLines.push(`; CalibBZ: ${coeffs.b.z.map(c => c.toFixed(6)).join(',')}`);
            }
        }
        processedLines.push('');

        for (const line of lines) {
            this.stats.totalLines++;
            processedLines.push(this.processLine(line, { ...options, applyIK, applyCalibration }));
        }

        return processedLines.join('\n');
    }

    /**
     * Process single G-code line
     */
    processLine(line, options = {}) {
        const trimmed = line.trim();

        // Skip empty lines, comments only
        if (!trimmed || trimmed.startsWith(';')) {
            return line;
        }

        // Track G90/G91 (absolute/relative positioning mode)
        if (trimmed.match(/^G90\b/i)) {
            this.isAbsolute = true;
            return line;
        }
        if (trimmed.match(/^G91\b/i)) {
            this.isAbsolute = false;
            return line;
        }

        // Handle G92 (set position) - update modal state
        if (trimmed.match(/^G92\s/i)) {
            this.handleG92(trimmed);
            return line;
        }

        // Only process G0/G1 movement commands
        if (!trimmed.match(/^G[01]\s/i) && !trimmed.match(/^G[01]$/i)) {
            return line;
        }

        // Parse the line
        const parsed = this.parseLine(trimmed);
        if (!parsed) return line;

        // Update modal state
        if (parsed.hasX) this.modalX = parsed.x;
        if (parsed.hasY) this.modalY = parsed.y;
        if (parsed.hasZ) this.modalZ = parsed.z;
        if (parsed.hasC) this.modalC = parsed.c;
        if (parsed.hasB) this.modalB = parsed.b;

        // Skip if no XYZ coordinates
        if (!parsed.hasX && !parsed.hasY && !parsed.hasZ) {
            return line;
        }

        // Skip corrections for relative moves (G91 mode)
        // Calibration and IK corrections only apply to absolute positions
        if (!this.isAbsolute) {
            return line;
        }

        // Get current position (use modal values for missing coordinates)
        let x = parsed.hasX ? parsed.x : this.modalX;
        let y = parsed.hasY ? parsed.y : this.modalY;
        let z = parsed.hasZ ? parsed.z : this.modalZ;
        const a = this.modalC;
        const b = this.modalB;

        let correctedX = x;
        let correctedY = y;
        let correctedZ = z;
        let wasIKCorrected = false;
        let wasCalibrationCorrected = false;

        // Step 1: Apply IK if enabled (converts tool-tip to machine coordinates)
        if (options.applyIK && this.ik && (a !== 0 || b !== 0)) {
            const ikResult = this.ik.apply(x, y, z, a, b);
            correctedX = ikResult.x;
            correctedY = ikResult.y;
            correctedZ = ikResult.z;
            wasIKCorrected = true;
        }

        // Step 2: Apply calibration correction if enabled
        if (options.applyCalibration && this.corrector?.loaded) {
            const correction = this.corrector.getCorrection(a, b);

            // Apply correction (no threshold - apply all corrections for consistency)
            // SUBTRACT error to compensate
            correctedX -= correction.x;
            correctedY -= correction.y;
            correctedZ -= correction.z;

            // Count as calibration-corrected if any correction was non-zero
            if (correction.x !== 0 || correction.y !== 0 || correction.z !== 0) {
                wasCalibrationCorrected = true;

                // Update max correction stats
                this.stats.maxCorrectionX = Math.max(this.stats.maxCorrectionX, Math.abs(correction.x));
                this.stats.maxCorrectionY = Math.max(this.stats.maxCorrectionY, Math.abs(correction.y));
                this.stats.maxCorrectionZ = Math.max(this.stats.maxCorrectionZ, Math.abs(correction.z));
            }
        }

        // Update statistics
        if (wasIKCorrected) this.stats.ikCorrectedLines++;
        if (wasCalibrationCorrected) this.stats.calibrationCorrectedLines++;
        if (wasIKCorrected || wasCalibrationCorrected) this.stats.processedLines++;

        // Rebuild the line with only the coordinates that were in the original
        return this.rebuildLine(parsed,
            parsed.hasX ? correctedX : null,
            parsed.hasY ? correctedY : null,
            parsed.hasZ ? correctedZ : null,
            options
        );
    }

    /**
     * Handle G92 command (set position)
     */
    handleG92(line) {
        const patterns = {
            x: /X([-+]?\d*\.?\d+)/i,
            y: /Y([-+]?\d*\.?\d+)/i,
            z: /Z([-+]?\d*\.?\d+)/i,
            c: /C([-+]?\d*\.?\d+)/i,
            b: /B([-+]?\d*\.?\d+)/i
        };

        for (const [axis, pattern] of Object.entries(patterns)) {
            const match = line.match(pattern);
            if (match) {
                const value = parseFloat(match[1]);
                this[`modal${axis.toUpperCase()}`] = value;
            }
        }
    }

    /**
     * Parse G-code line into components
     */
    parseLine(line) {
        const cmdMatch = line.match(/^(G[01])\s*/i);
        if (!cmdMatch) return null;

        const result = {
            command: cmdMatch[1].toUpperCase(),
            x: this.modalX, y: this.modalY, z: this.modalZ,
            a: this.modalC, b: this.modalB,
            hasX: false, hasY: false, hasZ: false, hasC: false, hasB: false,
            e: null, f: null,
            comment: null,
            original: line
        };

        // Extract comment
        const commentIdx = line.indexOf(';');
        let codePart = line;
        if (commentIdx !== -1) {
            result.comment = line.substring(commentIdx);
            codePart = line.substring(0, commentIdx);
        }

        // Parse coordinates
        const patterns = {
            x: /X([-+]?\d*\.?\d+)/i,
            y: /Y([-+]?\d*\.?\d+)/i,
            z: /Z([-+]?\d*\.?\d+)/i,
            c: /C([-+]?\d*\.?\d+)/i,
            b: /B([-+]?\d*\.?\d+)/i,
            e: /E([-+]?\d*\.?\d+)/i,
            f: /F([-+]?\d*\.?\d+)/i
        };

        for (const [axis, pattern] of Object.entries(patterns)) {
            const match = codePart.match(pattern);
            if (match) {
                const value = parseFloat(match[1]);
                result[axis] = value;
                if (['x', 'y', 'z', 'c', 'b'].includes(axis)) {
                    result[`has${axis.toUpperCase()}`] = true;
                }
            }
        }

        return result;
    }

    /**
     * Rebuild G-code line with corrected coordinates
     */
    rebuildLine(parsed, correctedX, correctedY, correctedZ, options = {}) {
        const precision = options.precision || 3;

        let line = parsed.command;

        if (correctedX !== null) {
            line += ` X${correctedX.toFixed(precision)}`;
        }
        if (correctedY !== null) {
            line += ` Y${correctedY.toFixed(precision)}`;
        }
        if (correctedZ !== null) {
            line += ` Z${correctedZ.toFixed(precision)}`;
        }
        if (parsed.hasC) {
            line += ` C${parsed.c.toFixed(1)}`;  // C/B use 1 decimal place (angular precision)
        }
        if (parsed.hasB) {
            line += ` B${parsed.b.toFixed(1)}`;  // C/B use 1 decimal place (angular precision)
        }
        if (parsed.e !== null) {
            line += ` E${parsed.e.toFixed(4)}`;
        }
        if (parsed.f !== null) {
            line += ` F${Math.round(parsed.f)}`;
        }

        if (parsed.comment) {
            line += ' ' + parsed.comment;
        }

        return line;
    }

    /**
     * Get processing statistics
     */
    getStatistics() {
        return { ...this.stats };
    }

    /**
     * Analyze corrections and return summary statistics
     */
    analyzeCorrections(gcode, options = {}) {
        this.reset();

        const applyIK = options.applyIK !== false && this.ik;
        const applyCalibration = options.applyCalibration !== false && this.corrector?.loaded;

        const lines = gcode.split('\n');

        // Track ranges
        let cRange = { min: Infinity, max: -Infinity };
        let bRange = { min: Infinity, max: -Infinity };

        // Track max corrections with their A/B values
        let maxIK = { x: { val: 0, a: 0, b: 0 }, y: { val: 0, a: 0, b: 0 }, z: { val: 0, a: 0, b: 0 } };
        let maxCalib = { x: { val: 0, a: 0, b: 0 }, y: { val: 0, a: 0, b: 0 }, z: { val: 0, a: 0, b: 0 } };

        let linesWithRotation = 0;

        for (const line of lines) {
            const trimmed = line.trim();

            // Handle G92
            if (trimmed.match(/^G92\s/i)) {
                this.handleG92(trimmed);
                continue;
            }

            if (!trimmed.match(/^G[01]\s/i)) continue;

            const parsed = this.parseLine(trimmed);
            if (!parsed) continue;

            // Update modal state
            if (parsed.hasX) this.modalX = parsed.x;
            if (parsed.hasY) this.modalY = parsed.y;
            if (parsed.hasZ) this.modalZ = parsed.z;
            if (parsed.hasC) this.modalC = parsed.c;
            if (parsed.hasB) this.modalB = parsed.b;

            if (!parsed.hasX && !parsed.hasY && !parsed.hasZ) continue;

            // Track A/B ranges
            if (this.modalC !== 0 || this.modalB !== 0) {
                linesWithRotation++;
                cRange.min = Math.min(cRange.min, this.modalC);
                cRange.max = Math.max(cRange.max, this.modalC);
                bRange.min = Math.min(bRange.min, this.modalB);
                bRange.max = Math.max(bRange.max, this.modalB);
            }

            let x = parsed.hasX ? parsed.x : this.modalX;
            let y = parsed.hasY ? parsed.y : this.modalY;
            let z = parsed.hasZ ? parsed.z : this.modalZ;

            if (applyIK && (this.modalC !== 0 || this.modalB !== 0)) {
                const ikResult = this.ik.apply(x, y, z, this.modalC, this.modalB);
                const dx = Math.abs(ikResult.x - x);
                const dy = Math.abs(ikResult.y - y);
                const dz = Math.abs(ikResult.z - z);

                if (dx > maxIK.x.val) maxIK.x = { val: dx, a: this.modalC, b: this.modalB };
                if (dy > maxIK.y.val) maxIK.y = { val: dy, a: this.modalC, b: this.modalB };
                if (dz > maxIK.z.val) maxIK.z = { val: dz, a: this.modalC, b: this.modalB };
            }

            if (applyCalibration && (this.modalC !== 0 || this.modalB !== 0)) {
                const corr = this.corrector.getCorrection(this.modalC, this.modalB);
                const dx = Math.abs(corr.x);
                const dy = Math.abs(corr.y);
                const dz = Math.abs(corr.z);

                if (dx > maxCalib.x.val) maxCalib.x = { val: dx, a: this.modalC, b: this.modalB };
                if (dy > maxCalib.y.val) maxCalib.y = { val: dy, a: this.modalC, b: this.modalB };
                if (dz > maxCalib.z.val) maxCalib.z = { val: dz, a: this.modalC, b: this.modalB };
            }
        }

        return {
            linesWithRotation,
            cRange: cRange.min !== Infinity ? cRange : null,
            bRange: bRange.min !== Infinity ? bRange : null,
            maxIK: applyIK ? maxIK : null,
            maxCalib: applyCalibration ? maxCalib : null
        };
    }
}

// Export for module use
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { GcodeProcessor };
}

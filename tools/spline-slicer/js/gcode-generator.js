// G-code generator for Rep5x Spline Slicer - converts slice contours to 5-axis G-code

class GcodeGenerator {
    constructor() {
        this.FILAMENT_DIAMETER = 1.75;
        this.contourProcessor = new ContourProcessor();
    }

    /**
     * Generate G-code from sliced contours
     * @param {Array} slices - Array of slice objects from MeshSlicer
     * @param {object} printSettings - Print settings from UI
     * @param {object} advancedSettings - Advanced settings from UI
     * @returns {object} {gcode, filename}
     */
    generate(slices, printSettings, advancedSettings) {
        const { layerHeight, speed, nozzleDiameter, nozzleTemp, bedTemp,
                bedWidth, bedDepth, wallCount, infillDensity } = printSettings;
        const { enableCAxisOptimization, ikMode = 'live', startGcode, endGcode } = advancedSettings;

        const gcode = [];
        const bedCenterX = bedWidth / 2;
        const bedCenterY = bedDepth / 2;

        // Process start/end G-code - replace placeholders
        const processedStartGcode = this.processTemplatePlaceholders(startGcode, {
            nozzleTemp, bedTemp, bedCenterX, bedCenterY
        });
        const processedEndGcode = this.processTemplatePlaceholders(endGcode, {
            nozzleTemp, bedTemp
        });

        // Header
        gcode.push('; Generated by Rep5x Spline Slicer');
        gcode.push(`; Slices: ${slices.length}`);
        gcode.push(`; Nozzle Diameter: ${nozzleDiameter}mm`);
        gcode.push(`; Layer Height: ${layerHeight}mm`);
        gcode.push(`; Print Speed: ${speed / 60}mm/s`);
        gcode.push(`; Walls: ${wallCount}`);
        gcode.push(`; Infill: ${infillDensity}%`);
        gcode.push(`; Generated on: ${new Date().toISOString()}`);
        gcode.push('');

        // 5-axis parameters
        gcode.push('; === Rep5x Parameters ===');
        const ikModeLabel = ikMode === 'preprocess' ? 'pre-processed (M668)' :
                            ikMode === 'live' ? 'live (G43.4)' : 'none';
        gcode.push(`; IK Mode: ${ikModeLabel}`);
        gcode.push(`; C-axis Optimization: ${enableCAxisOptimization ? 'enabled' : 'disabled'}`);
        gcode.push('');

        // Start sequence
        gcode.push('; Start sequence');
        if (processedStartGcode.trim()) {
            gcode.push(...processedStartGcode.split('\n'));
        } else {
            this.addDefaultStartGcode(gcode, ikMode, nozzleTemp, bedTemp, bedCenterX, bedCenterY);
        }
        gcode.push('M83 ; Use relative extrusion');
        gcode.push('');

        // Generate slice G-code
        gcode.push('; === Spline Slicer G-code ===');
        let prevPos = null;
        const filamentArea = Math.PI * Math.pow(this.FILAMENT_DIAMETER / 2, 2);

        let prevSliceDistance = 0;
        let prevCoords = null; // Track plane basis for continuous parallel transport

        for (let s = 0; s < slices.length; s++) {
            const slice = slices[s];
            const normal = slice.normal || slice.tangent;

            // Actual layer height = distance between this slice and the previous one
            // With adaptive sampling, slices may be closer or farther apart than nominal
            const sliceDistance = slice.distance != null ? slice.distance : s * layerHeight;
            const actualLayerHeight = s > 0
                ? Math.min(Math.max(sliceDistance - prevSliceDistance, layerHeight * 0.1), layerHeight * 3)
                : layerHeight;
            prevSliceDistance = sliceDistance;

            // Calculate C and B angles from slice normal (Three.js Y-up)
            const B = Math.acos(Math.max(-1, Math.min(1, normal.y))) * 180 / Math.PI;
            const C = Math.atan2(-normal.z, normal.x) * 180 / Math.PI;

            gcode.push(`; --- Slice ${s} (B=${B.toFixed(1)} C=${C.toFixed(1)}) ---`);

            // Process contours into walls and infill
            // Pass prevCoords for continuous basis (parallel transport prevents basis flips)
            const { walls, infill, coords } = this.contourProcessor.process(
                slice.contours,
                normal,
                slice.point,
                { wallCount: wallCount || 1, nozzleDiameter, infillDensity: infillDensity || 0 },
                s,
                prevCoords
            );
            prevCoords = coords;

            // Generate wall G-code
            for (let w = 0; w < walls.length; w++) {
                const wall = walls[w];
                if (wall.length < 3) continue;

                gcode.push(`; Wall ${w + 1}`);
                prevPos = this._generateContourGcode(
                    gcode, wall, B, C, prevPos, actualLayerHeight,
                    nozzleDiameter, filamentArea, speed, s === 0 && w === 0
                );
            }

            // Generate infill G-code (zigzag to minimise travel)
            if (infill.length > 0) {
                gcode.push('; Infill');
                for (let i = 0; i < infill.length; i++) {
                    const line = infill[i];
                    // Alternate direction for zigzag
                    const start = (i % 2 === 0) ? line.a : line.b;
                    const end = (i % 2 === 0) ? line.b : line.a;

                    // Travel to line start
                    const gs = this._toGcode(start);
                    gcode.push(`G0 X${gs.x.toFixed(3)} Y${gs.y.toFixed(3)} Z${gs.z.toFixed(3)} C${C.toFixed(3)} B${B.toFixed(3)}`);
                    prevPos = gs;

                    // Extrude to line end
                    const ge = this._toGcode(end);
                    const dist = this._distance3D(prevPos, ge);
                    const deltaE = dist * (actualLayerHeight * nozzleDiameter) / filamentArea;
                    gcode.push(`G1 X${ge.x.toFixed(3)} Y${ge.y.toFixed(3)} Z${ge.z.toFixed(3)} C${C.toFixed(3)} B${B.toFixed(3)} E${deltaE.toFixed(4)} F${Math.round(speed)}`);
                    prevPos = ge;
                }
            }
        }

        // End sequence
        gcode.push('');
        gcode.push('; End sequence');
        if (processedEndGcode.trim()) {
            gcode.push(...processedEndGcode.split('\n'));
        } else {
            this.addDefaultEndGcode(gcode);
        }

        let gcodeString = gcode.join('\n');

        // Apply C-axis optimization if enabled
        if (enableCAxisOptimization) {
            gcodeString = optimizeCAxisRotation(gcodeString, enableCAxisOptimization);
            gcodeString = addCAxisOptimizationComment(gcodeString);
        }

        return {
            gcode: gcodeString,
            filename: `rep5x_spline-slicer_${slices.length}slices.gcode`
        };
    }

    /**
     * Generate G-code for a closed contour (wall)
     * Returns the last position
     */
    _generateContourGcode(gcode, contour, B, C, prevPos, layerHeight, nozzleDiameter, filamentArea, speed, isFirst) {
        for (let p = 0; p < contour.length; p++) {
            const pt = contour[p];
            const pos = this._toGcode(pt);

            if (p === 0) {
                if (isFirst && prevPos === null) {
                    gcode.push(`G0 X${pos.x.toFixed(3)} Y${pos.y.toFixed(3)} Z${pos.z.toFixed(3)} C${C.toFixed(3)} B${B.toFixed(3)} ; move to start`);
                } else {
                    gcode.push(`G0 X${pos.x.toFixed(3)} Y${pos.y.toFixed(3)} Z${pos.z.toFixed(3)} C${C.toFixed(3)} B${B.toFixed(3)}`);
                }
            } else {
                const dist = this._distance3D(prevPos, pos);
                const deltaE = dist * (layerHeight * nozzleDiameter) / filamentArea;
                gcode.push(`G1 X${pos.x.toFixed(3)} Y${pos.y.toFixed(3)} Z${pos.z.toFixed(3)} C${C.toFixed(3)} B${B.toFixed(3)} E${deltaE.toFixed(4)} F${Math.round(speed)}`);
            }

            prevPos = pos;
        }

        // Close the contour
        if (contour.length > 2) {
            const firstPos = this._toGcode(contour[0]);
            const dist = this._distance3D(prevPos, firstPos);
            const deltaE = dist * (layerHeight * nozzleDiameter) / filamentArea;
            gcode.push(`G1 X${firstPos.x.toFixed(3)} Y${firstPos.y.toFixed(3)} Z${firstPos.z.toFixed(3)} C${C.toFixed(3)} B${B.toFixed(3)} E${deltaE.toFixed(4)} F${Math.round(speed)}`);
            prevPos = firstPos;
        }

        return prevPos;
    }

    /** Transform a Three.js point to G-code coordinates */
    _toGcode(pt) {
        return { x: pt.x, y: -pt.z, z: pt.y };
    }

    _distance3D(p1, p2) {
        return Math.sqrt(
            Math.pow(p1.x - p2.x, 2) +
            Math.pow(p1.y - p2.y, 2) +
            Math.pow(p1.z - p2.z, 2)
        );
    }

    processTemplatePlaceholders(template, values) {
        if (!template) return '';

        let result = template;

        // OrcaSlicer/BambuStudio style placeholders
        result = result.replace(/\[nozzle_temperature_initial_layer\]/g, values.nozzleTemp || 210);
        result = result.replace(/\[bed_temperature_initial_layer_single\]/g, values.bedTemp || 60);
        result = result.replace(/\[bed_center_x\]/g, values.bedCenterX || 100);
        result = result.replace(/\[bed_center_y\]/g, values.bedCenterY || 100);

        // Hardcoded M-codes (fallback)
        if (values.nozzleTemp) {
            result = result.replace(/M104 S\d+/g, `M104 S${values.nozzleTemp}`);
            result = result.replace(/M109 S\d+/g, `M109 S${values.nozzleTemp}`);
        }
        if (values.bedTemp) {
            result = result.replace(/M140 S\d+/g, `M140 S${values.bedTemp}`);
            result = result.replace(/M190 S\d+/g, `M190 S${values.bedTemp}`);
        }

        return result;
    }

    addDefaultStartGcode(gcode, ikMode = 'live', nozzleTemp = 210, bedTemp = 60, bedCenterX = 100, bedCenterY = 100) {
        if (ikMode === 'preprocess') {
            gcode.push('G49 ; Disable IK');
            gcode.push('M667 S0 ; Disable calibration');
            gcode.push(`M668 B${bedTemp} H${nozzleTemp} ; Pre-process IK + start heating`);
        } else {
            gcode.push('G49 ; Disable IK during homing');
            gcode.push('M667 S0 ; Disable calibration during homing');
            gcode.push(`M104 S${nozzleTemp} ; Set hotend temp`);
            gcode.push(`M140 S${bedTemp} ; Set bed temp`);
        }
        gcode.push('G28 ; Home all axes');
        gcode.push('G92 E0 ; Reset extruder');
        gcode.push('G1 Z2 F3000 ; Lift Z');
        gcode.push(`M190 S${bedTemp} ; Wait for bed`);
        gcode.push(`M109 S${nozzleTemp} ; Wait for hotend`);
        gcode.push('G1 E10 F200 ; Prime extruder');
        gcode.push('G92 E0 ; Reset extruder');
        gcode.push('G21 ; Set units to millimeters');
        gcode.push('G90 ; Use absolute coordinates');
        gcode.push(`G0 X${bedCenterX} Y${bedCenterY} F2400 ; Move to bed centre`);
        gcode.push('G92 X0 Y0 C0 B0 ; Set bed centre as origin');
        gcode.push('M211 S0 ; Disable software endstops');
        if (ikMode === 'live') {
            gcode.push('G43.4 ; Enable IK');
            gcode.push('M667 S1 ; Enable calibration');
            gcode.push('M205 I2 J2 ; Lower C/B jerk for smooth 5-axis movement');
        }
    }

    addDefaultEndGcode(gcode) {
        gcode.push('G1 E-2 F1800 ; Retract filament');
        gcode.push('G49 ; Disable IK before homing');
        gcode.push('M667 S0 ; Disable calibration');
        gcode.push('G28 Z ; Home Z');
        gcode.push('G0 C0 B0 ; Return rotation axes to 0');
        gcode.push('M104 S0 ; Turn off hotend');
        gcode.push('M140 S0 ; Turn off bed');
        gcode.push('M84 ; Disable motors');
        gcode.push('M117 Print Complete! ; Display message');
    }
}
